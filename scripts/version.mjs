// Generate self-contained MoonBit provenance; no Git or network needed at runtime.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const module=readFileSync(new URL('moon.mod',root),'utf8');
const version=module.match(/^version\s*=\s*"([^"]+)"/m)[1];
if(JSON.parse(readFileSync(new URL('package.json',root),'utf8')).version!==version)throw Error('Package versions disagree');
const paths=[...readdirSync(root).filter(p=>p.endsWith('.mbt')&&!p.includes('test')&&p!=='version.mbt'),'moon.mod','moon.pkg','bridge/main.mbt','bridge/moon.pkg'].sort();
const hash=createHash('sha256');
for(const path of paths)hash.update(path+'\0').update(readFileSync(new URL(path,root),'utf8').replace(/\r\n/g,'\n')).update('\0');
const digest=hash.digest('hex');
const source=`// Generated by node scripts/version.mjs --write; committed for plain moon consumers.

///|
/// Build provenance describes the compiled engine, independently of the host.
pub fn generator_json() -> Json {
  {
    "name": "MoonCam",
    "version": "${version}",
    "source_digest": "sha256:${digest}",
  }
}
`;
const target=new URL('version.mbt',root);
if(process.argv.includes('--write'))writeFileSync(target,source);
else if(readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==source)throw Error('Stale engine provenance. Run node scripts/version.mjs --write, then moon fmt and moon info.');
console.log(`MoonCam ${version}; engine sha256:${digest}`);
